#!/usr/bin/env python3
"""Fail-closed integrity intake for *actual* source payload bytes.

This checks original bytes *supplied by an authorized owner* against a
claimed checksum and separately recorded clocks. It does not independently
verify publisher identity, original first-publication, revisions, data rights,
historical point-in-time availability, mappings or portfolio risk approval.

It is deliberately local and read-only; no MotherDuck write, data export,
external request, auto-license assertion or autogenerated evidence.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timedelta, timezone
import hashlib
import json
from pathlib import Path
import re
import sys
from urllib.parse import parse_qsl, urlsplit

VERSION = "phase1-source-evidence-integrity-v1.0.0"
MAX_PAYLOAD_BYTES = 50 * 1024 * 1024
CLOCK_SKEW = timedelta(minutes=5)
ALLOWED_SOURCE_FAMILIES = frozenset((
    "venue_prospective_receipts", "historical_market_snapshots",
    "usd_security_prices", "treasury_par_yields",
    "us_equity_style_factors", "ecb_eur_fx_reference",
    "nyfed_sofr_effr_reference", "fred_macro_economic",
    "security_corporate_actions", "independent_tradeable_fx",
    "licensed_credit_spreads", "commodities_futures_rolls",
    "options_volatility", "portfolio_positions",
    "macro_release_consensus", "event_evidence_archive",
))
REQUIRED = frozenset((
    "source_family", "source_record_id", "source_uri", "payload_path",
    "payload_sha256", "capture_received_at", "warehouse_registered_at",
))
OPTIONAL = frozenset((
    "provider_published_at", "provider_revision_at",
    "source_observation_date", "source_version",
))
HEX64 = re.compile(r"^[0-9a-f]{64}$")
RECORD_ID = re.compile(r"^[A-Za-z0-9_:./-]{1,200}$")
DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
SENSITIVE_QUERY = frozenset((
    "token", "access_token", "apikey", "api_key", "key", "password",
    "secret", "credential", "authorization", "signature", "sig",
))


class PacketRejected(ValueError):
    """Invalid source-integrity packet; never reinterpret as source approval."""


def clock(value: str, name: str, now: datetime) -> datetime:
    if not isinstance(value, str) or len(value) > 45:
        raise PacketRejected(f"{name}: nonempty ISO-8601 timezone-aware value required")
    try:
        dt = datetime.fromisoformat(value.replace("Z", "+00:00"))
    except ValueError as exc:
        raise PacketRejected(f"{name}: invalid ISO-8601 clock") from exc
    if dt.tzinfo is None or dt.utcoffset() is None:
        raise PacketRejected(f"{name}: naive clock prohibited")
    utc = dt.astimezone(timezone.utc)
    if utc > now + CLOCK_SKEW or utc.year < 1990:
        raise PacketRejected(f"{name}: invalid historical or future time")
    return utc


def source_uri(uri: str) -> str:
    if not isinstance(uri, str) or len(uri) > 2048:
        raise PacketRejected("source_uri: URL required")
    try:
        parsed = urlsplit(uri)
        hostname = parsed.hostname
        params = parse_qsl(parsed.query, keep_blank_values=True)
    except ValueError as exc:
        raise PacketRejected("source_uri: invalid authority or URL") from exc
    if (parsed.scheme.lower() != "https" or not hostname
        or parsed.username is not None or parsed.password is not None
        or any(k.lower() in SENSITIVE_QUERY for k, _ in params)):
        raise PacketRejected("source_uri: require HTTPS without credentials")
    # Returned string is deliberately sanitized; payload/manifest secrets and
    # query values are never printed or included in an evidence ledger.
    return f"https://{hostname.lower()}{parsed.path}"


def payload_digest(path_text: str, root: Path) -> tuple[str, int]:
    if (not isinstance(path_text, str) or not path_text
        or len(path_text) > 1024):
        raise PacketRejected("payload_path: local relative file required")
    raw = Path(path_text)
    if raw.is_absolute() or ".." in raw.parts:
        raise PacketRejected("payload_path: absolute or traversal path prohibited")
    base = root.resolve(strict=True)
    dest = (base / raw).resolve(strict=True)
    if not dest.is_relative_to(base) or not dest.is_file():
        raise PacketRejected("payload_path: file outside approved intake root")
    size = dest.stat().st_size
    if size <= 0 or size > MAX_PAYLOAD_BYTES:
        raise PacketRejected("payload_path: empty or oversized source content")
    digest = hashlib.sha256()
    total = 0
    with dest.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            total += len(chunk)
            if total > MAX_PAYLOAD_BYTES:
                raise PacketRejected("payload_path: maximum payload bytes exceeded")
            digest.update(chunk)
    if total != size:
        raise PacketRejected("payload_path: source changed during read")
    return digest.hexdigest(), total


def validate(packet: dict, root: Path, *, now: datetime | None = None) -> dict:
    """Cryptographic byte integrity is checked; original-source authenticity isn't.

    Caller must obtain original provider/publisher timestamps and verify them
    independently outside this automatic integrity step. No caller-supplied
    approval flag is recognized, even if its value is false.
    """
    if now is None:
        now = datetime.now(timezone.utc)
    if now.tzinfo is None or now.utcoffset() is None:
        raise PacketRejected("Runtime reference time must be timezone-aware")
    now = now.astimezone(timezone.utc)
    if not isinstance(packet, dict) or set(packet) - (REQUIRED | OPTIONAL):
        raise PacketRejected("Unsupported packet fields, including approval claims")
    if REQUIRED - set(packet):
        raise PacketRejected("Required evidence metadata missing")
    family = packet["source_family"]
    if family not in ALLOWED_SOURCE_FAMILIES:
        raise PacketRejected("Unregistered source family")
    record = packet["source_record_id"]
    if not isinstance(record, str) or not RECORD_ID.fullmatch(record):
        raise PacketRejected("Invalid source record identifier")
    expected = packet["payload_sha256"]
    if not isinstance(expected, str) or not HEX64.fullmatch(expected):
        raise PacketRejected("SHA256 must be 64 lowercase hex characters")
    safe_uri = source_uri(packet["source_uri"])
    received = clock(packet["capture_received_at"], "capture_received_at", now)
    registered = clock(packet["warehouse_registered_at"], "warehouse_registered_at", now)
    if registered < received:
        raise PacketRejected("Warehouse registration cannot precede recorded receipt")
    published_raw = packet.get("provider_published_at")
    revised_raw = packet.get("provider_revision_at")
    published = (clock(published_raw, "provider_published_at", now)
                 if published_raw is not None else None)
    revised = (clock(revised_raw, "provider_revision_at", now)
               if revised_raw is not None else None)
    if published and published > received:
        raise PacketRejected("Claimed provider publication later than receipt")
    if revised and (published is None or revised < published or revised > received):
        raise PacketRejected("Invalid claimed revision/publication order")
    observation = packet.get("source_observation_date")
    if observation is not None:
        if not isinstance(observation, str) or not DATE.fullmatch(observation):
            raise PacketRejected("Source observation date must use YYYY-MM-DD")
        from datetime import date
        try:
            date.fromisoformat(observation)
        except ValueError as exc:
            raise PacketRejected("Source observation date invalid") from exc
    version = packet.get("source_version")
    if version is not None and (not isinstance(version, str)
                                or not 1 <= len(version) <= 200):
        raise PacketRejected("Source version must be a bounded string")
    actual, length = payload_digest(packet["payload_path"], root)
    if actual != expected:
        raise PacketRejected("Payload SHA256 mismatch; bytes not accepted")
    stable = "|".join((family, record, expected, received.isoformat(), safe_uri))
    packet_id = hashlib.sha256(stable.encode("utf-8")).hexdigest()
    return {
        "intake_version": VERSION,
        "packet_id": packet_id,
        "source_family": family,
        "source_record_id": record,
        "source_uri_redacted": safe_uri,
        "source_version": version,
        "source_observation_date": observation,
        "source_sha256": actual,
        "payload_byte_count": length,
        "local_payload_sha256_integrity_pass": True,
        "http_or_local_capture_received_at": received.isoformat(),
        "warehouse_registered_at_claim": registered.isoformat(),
        "provider_publication_clock_claimed_at": (
            published.isoformat() if published else None
        ),
        "provider_revision_clock_claimed_at": (
            revised.isoformat() if revised else None
        ),
        "provider_publication_independently_verified": False,
        "original_provider_payload_authenticity_independently_verified": False,
        "first_available_to_market_independently_verified": False,
        "commercial_data_rights_approved": False,
        "independent_second_reviewer_approved": False,
        "event_factor_mapping_approved": False,
        "historical_pit_backtest_released": False,
        "institutional_risk_use_approved": False,
        "disposition": "SOURCE_BYTES_MATCH_CLAIM_ONLY_EXTERNAL_REVIEW_REQUIRED",
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--packet", required=True, type=Path,
                        help="Local JSON metadata file, not remotely fetched")
    parser.add_argument("--root", required=True, type=Path,
                        help="Approved local source-payload root directory")
    args = parser.parse_args(argv)
    try:
        packet = json.loads(args.packet.read_text(encoding="utf-8"))
        result = validate(packet, args.root)
    except (PacketRejected, OSError, ValueError, TypeError) as exc:
        # Report only concise error class; no vendor payload or URI credentials.
        print(f"PACKET_REJECTED: {type(exc).__name__}", file=sys.stderr)
        return 2
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
